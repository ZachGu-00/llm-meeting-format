"""Pinned checkpoint downloads and audited rotation after dependent evidence closes."""
import json
from pathlib import Path
import shutil
import subprocess
import sys
from common import load, sha, verify_bindings, write_new
from checkpoint import safe_relative, verify_checkpoint

RESERVE = 12 * 1024 ** 3

def verify_manifest(path, repo, revision):
    root = Path(path); manifest = load(root / 'snapshot_manifest.json')
    if (manifest.get('status') != 'complete' or manifest['repo_id'] != repo or manifest['revision'] != revision
        or (root / 'RESEARCH_REVISION.txt').read_text().strip() != revision):
        raise ValueError('Checkpoint manifest identity mismatch')
    missing = []
    for name, spec in manifest['files'].items():
        p = safe_relative(root, name)
        if not p.exists(): missing.append(name); continue
        if p.is_symlink() or not p.is_file() or p.stat().st_size != spec['bytes'] or sha(p) != spec['sha256']:
            raise ValueError('Checkpoint bytes differ from the pinned download: ' + name)
    return manifest, missing

def prepare(base, extension, model):
    root = Path(extension); destination = Path(model['model_dir'])
    if destination.resolve() != root.resolve() / 'expanded_models' / model['slug']:
        raise ValueError('Unexpected expanded checkpoint path')
    manifest_path = destination / 'snapshot_manifest.json'
    if manifest_path.exists():
        manifest, missing = verify_manifest(destination, model['repo_id'], model['revision'])
        if missing:
            # An existing identity is never regenerated by the downloader's timestamped manifest.
            if any(not name.endswith('.safetensors') for name in missing):
                raise ValueError('Checkpoint metadata unexpectedly absent')
            needed = sum(manifest['files'][name]['bytes'] for name in missing)
            if shutil.disk_usage(root).free - needed < RESERVE + 2 * 1024 ** 3:
                raise OSError('Restore would violate storage reserve plus output allowance')
            from huggingface_hub import hf_hub_download
            token_path = Path('/workspace/.hf_home/token')
            token = token_path.read_text().strip() if token_path.exists() else None
            for name in missing:
                try: hf_hub_download(model['repo_id'], name, revision=model['revision'], local_dir=destination, token=token)
                except Exception as error:
                    code = getattr(getattr(error, 'response', None), 'status_code', None)
                    raise RuntimeError('Pinned restore failed: ' + type(error).__name__ + '; HTTP ' + str(code)) from None
            _, absent = verify_manifest(destination, model['repo_id'], model['revision'])
            if absent: raise ValueError('Restored checkpoint remains incomplete')
        return {'status': 'verified_existing_identity', 'manifest_sha256': sha(manifest_path)}
    if shutil.disk_usage(root).free - model['weight_bytes'] < RESERVE + 2 * 1024 ** 3:
        raise OSError('New checkpoint would violate storage reserve plus output allowance')
    log = root / 'plans/expansion/download_logs' / (model['slug'] + '.log'); log.parent.mkdir(parents=True, exist_ok=True)
    with log.open('a') as handle:
        result = subprocess.run([sys.executable, str(Path(base) / 'setup/download_model.py'), '--repo', model['repo_id'],
            '--revision', model['revision'], '--root', str(destination.parent)], stdout=handle, stderr=subprocess.STDOUT)
    if result.returncode: raise RuntimeError('Pinned model download failed; inspect retained private download log')
    manifest, absent = verify_manifest(destination, model['repo_id'], model['revision'])
    if absent: raise ValueError('Downloader returned an incomplete checkpoint')
    return {'status': 'downloaded_and_all_SHA256_verified', 'manifest_sha256': sha(manifest_path),
            'bytes': sum(x['bytes'] for x in manifest['files'].values())}

def validate_ack(info, ack):
    if (ack.get('schema') != 'voices_v3_off_server_backup_ack_v1' or
        ack.get('all_member_and_source_hashes_verified') is not True or
        any(ack.get(k) != info[k] for k in ('archive_sha256', 'analysis_sha256', 'repo_id'))):
        raise ValueError('Exact source-verified independent backup acknowledgement is required')

def unused(path):
    for process in Path('/proc').glob('[0-9]*'):
        try: args = (process / 'cmdline').read_bytes().split(b'\0')
        except OSError: continue
        if str(path).encode() in args: return False
    return True

def rotate(path, model, info, ack, receipt_root, expected_parent, dependency_scope):
    path, parent = Path(path), Path(expected_parent).resolve()
    if path.is_symlink() or path.resolve() != parent / model['slug']:
        raise ValueError('Refusing rotation outside the exact registered checkpoint path')
    validate_ack(info, ack)
    if not unused(path): raise RuntimeError('Checkpoint is in use; preserve weights')
    manifest, missing = verify_manifest(path, model['repo_id'], model['revision'])
    if model.get('engine') and sha(path / 'snapshot_manifest.json') != model['engine']['parent_loader']['snapshot_manifest_sha256']:
        raise ValueError('Rotation manifest differs from calibrated native model')
    folder = Path(receipt_root); plan_path = folder / (model['slug'] + '_release_plan.json')
    if missing and not plan_path.exists(): raise ValueError('Unexpected missing checkpoint bytes before registered rotation')
    if any(not name.endswith('.safetensors') for name in missing): raise ValueError('Checkpoint metadata is missing')
    weights = {n: s for n, s in manifest['files'].items() if n.endswith('.safetensors')}
    record = {'schema': 'voices_v3_completed_checkpoint_rotation_v1', 'repo_id': model['repo_id'],
        'revision': model['revision'], 'checkpoint': str(path), 'manifest_sha256': sha(path / 'snapshot_manifest.json'),
        'archive_sha256': info['archive_sha256'], 'analysis_sha256': info['analysis_sha256'],
        'weight_files': weights, 'dependency_scope': dependency_scope,
        'preserved': 'all raw results, input/source/calibration/metadata, snapshot manifest and failed attempts',
        'restoration': 'official pinned revision; exact original safetensors SHA-256 required'}
    write_new(plan_path, record)
    for name, spec in weights.items():
        p = safe_relative(path, name)
        if p.exists():
            if p.is_symlink() or sha(p) != spec['sha256']: raise ValueError('Unexpected file preserved')
            p.unlink()
    receipt = {**record, 'status': 'reproducible_weight_bytes_rotated',
               'bytes_released': sum(s['bytes'] for s in weights.values())}
    write_new(folder / (model['slug'] + '_release_receipt.json'), receipt)
    return receipt

def rotate_initial_after_e9(registration):
    plan = load(registration); base, root = Path(plan['base']), Path(plan['extension'])
    original = load(plan['predecessor_plan']); terminal = load(Path(plan['predecessor_plan']).parent / 'final_status.json')
    if (terminal.get('status') != 'complete_E9_initial10' or terminal.get('plan_sha256') != plan['predecessor_plan_sha256']
        or terminal.get('E9_initial10_complete') is not True): raise ValueError('Initial E9 must close before original weights can rotate')
    report = load(terminal['report']['json']); verify_bindings(report['source_sha256'])
    if sha(terminal['report']['json']) != terminal['report']['sha256']: raise ValueError('Initial E9 report changed')
    from e9_queue import e4_closed
    if not e4_closed(original): raise ValueError('Original E4 not closed')
    index = load(root / 'archives/index.json')['archives']; by_model = {i['repo_id']: i for i in index.values()}
    receipts = []
    for model in original['models']:
        if model['execution_model_dir'] != model['model_dir']: continue
        if model['repo_id'] not in by_model: return {'status': 'waiting_for_verified_backup', 'model': model['repo_id']}
        info = by_model[model['repo_id']]; ack_path = root / 'archives/off_server_ack' / (info['archive_sha256'] + '.json')
        if not ack_path.exists(): return {'status': 'waiting_for_verified_backup', 'model': model['repo_id']}
        receipts.append(rotate(model['model_dir'], model, info, load(ack_path), root / 'provenance/initial_weight_rotation',
            base / 'models', 'Original full E4 and initial10 full E9 closed; independent complete model evidence backup verified'))
    return {'status': 'initial_dependencies_closed_and_weights_rotated', 'receipts': receipts}
